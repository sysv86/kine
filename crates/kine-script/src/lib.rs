//! `kine-script` — the agent-facing authoring layer.
//!
//! Pipeline: TypeScript source → (oxc) TypeScript-stripped JS → QuickJS
//! evaluation of a typed DSL → JSON scene description → [`kine_core::Scene`].

pub mod authoring;
pub mod runtime;
pub mod transpile;

pub use authoring::{
    parse_color, scene_from_def, AnimationDef, AudioDef, AudioTrackDef, AuthoringError,
    CompressorDef, EdgesDef, EqBandDef, GradientDef, GradientStopDef, KeyframeDef, NodeDef,
    SceneDef, SizeDef,
};
pub use runtime::{
    eval_scene_def_js, eval_scene_def_ts, eval_scene_js, eval_scene_ts, PRELUDE,
};
pub use transpile::transpile_ts;

/// Complete TypeScript `.d.ts` ambient declaration schema for the Kine DSL
/// (`kine types --out kine.d.ts`).
pub const KINE_DTS: &str = r#"// Generated by Kine Engine — Video-as-Code TypeScript Ambient Declarations

export type EasingName =
  | "linear"
  | "easeIn"
  | "easeOut"
  | "easeInOut"
  | "easeOutCubic"
  | "easeInOutCubic"
  | "spring"
  | `spring(${number}, ${number})`
  | `cubic-bezier(${number}, ${number}, ${number}, ${number})`
  | `steps(${number})`;

export interface KeyframeSpec {
  time: number;
  value: number;
}

export interface AnimationSpec {
  from?: number;
  to?: number;
  start?: number;
  end?: number;
  keyframes?: KeyframeSpec[];
  easing?: EasingName;
}

export type AnimatableProperty =
  | "offsetX"
  | "offsetY"
  | "width"
  | "height"
  | "opacity"
  | "translateX"
  | "translateY"
  | "scale"
  | "scaleX"
  | "scaleY"
  | "rotation"
  | "cornerRadius"
  | "fontSize";

export interface SizeSpec {
  width?: number;
  height?: number;
}

export interface EdgesSpec {
  top?: number;
  left?: number;
  right?: number;
  bottom?: number;
}

export interface GradientStopSpec {
  offset: number;
  color: string;
}

export interface GradientSpec {
  kind?: "linear" | "radial";
  angle?: number;
  stops: GradientStopSpec[];
}

export interface LayoutProps {
  size?: SizeSpec;
  minSize?: SizeSpec;
  maxSize?: SizeSpec;
  inset?: EdgesSpec;
  margin?: EdgesSpec;
  padding?: EdgesSpec;
  position?: "relative" | "absolute";
  flexDirection?: "row" | "column" | "row-reverse" | "column-reverse";
  flexWrap?: "nowrap" | "wrap" | "wrap-reverse";
  flexGrow?: number;
  flexShrink?: number;
  flexBasis?: number;
  justifyContent?: "start" | "center" | "end" | "space-between" | "space-around" | "space-evenly";
  alignItems?: "start" | "center" | "end" | "stretch";
  alignSelf?: "start" | "center" | "end" | "stretch";
  gap?: number;
  aspectRatio?: number;
  overflow?: "visible" | "hidden";
  opacity?: number;
  translateX?: number;
  translateY?: number;
  scale?: number;
  scaleX?: number;
  scaleY?: number;
  rotation?: number;
  strokeColor?: string;
  strokeWidth?: number;
  shadowColor?: string;
  shadowBlur?: number;
  shadowOffsetX?: number;
  shadowOffsetY?: number;
  gradient?: GradientSpec;
  animate?: Partial<Record<AnimatableProperty, AnimationSpec>>;
}

export interface RectProps extends LayoutProps {
  fill?: string;
  cornerRadius?: number;
}

export interface CircleProps extends LayoutProps {
  fill?: string;
  radius?: number;
}

export interface PathProps extends LayoutProps {
  fill?: string;
}

export interface ImageProps extends LayoutProps {
  objectFit?: "cover" | "contain" | "fill";
  cornerRadius?: number;
}

export interface VideoProps extends LayoutProps {
  objectFit?: "cover" | "contain" | "fill";
  cornerRadius?: number;
  start?: number;
  trimStart?: number;
  trimEnd?: number;
  playbackRate?: number;
  loop?: boolean;
}

export interface TextProps extends LayoutProps {
  fontFamily?: string;
  fontSize?: number;
  fontWeight?: number;
  color?: string;
  align?: "left" | "center" | "right";
}

export interface ShaderProps extends LayoutProps {
  blend?: "normal" | "add" | "multiply" | "screen";
  uniforms?: Record<string, number | number[]>;
}

export interface EqBandSpec {
  kind: "lowpass" | "highpass" | "bandpass" | "notch" | "peaking" | "lowshelf" | "highshelf";
  freqHz: number;
  q?: number;
  gainDb?: number;
}

export interface CompressorSpec {
  thresholdDb?: number;
  ratio?: number;
  attackMs?: number;
  releaseMs?: number;
  makeupDb?: number;
}

export interface AudioTrackSpec {
  src: string;
  gainDb?: number;
  start?: number;
  trimStart?: number;
  trimEnd?: number;
  loop?: boolean;
  pan?: number;
  fadeIn?: number;
  fadeOut?: number;
  fadeCurve?: "linear" | "equalPower" | "sCurve" | "exponential";
  highpassHz?: number;
  lowpassHz?: number;
  eq?: EqBandSpec[];
  compressor?: CompressorSpec;
  duckDb?: number;
  duckThresholdDb?: number;
  muted?: boolean;
}

export interface AudioBedSpec {
  sampleRate?: number;
  channels?: number;
  normalizePeakDb?: number;
  tracks: AudioTrackSpec[];
}

export interface SceneOptions {
  audio?: AudioBedSpec;
}

export interface SceneNode {
  kind: string;
  children?: SceneNode[];
  [key: string]: unknown;
}

export interface SceneDef extends SceneOptions {
  width: number;
  height: number;
  root: SceneNode;
}

declare global {
  function scene(width: number, height: number, root: SceneNode, opts?: SceneOptions): SceneDef;
  function container(opts?: LayoutProps, children?: SceneNode[]): SceneNode;
  function rect(opts?: RectProps): SceneNode;
  function circle(opts?: CircleProps): SceneNode;
  function path(d: string, opts?: PathProps): SceneNode;
  function image(src: string, opts?: ImageProps): SceneNode;
  function video(src: string, opts?: VideoProps): SceneNode;
  function text(content: string, opts?: TextProps): SceneNode;
  function shader(wgsl: string, opts?: ShaderProps): SceneNode;
  function linearGradient(angle: number, stops: GradientStopSpec[]): GradientSpec;
  function radialGradient(stops: GradientStopSpec[]): GradientSpec;
  function spring(stiffness?: number, damping?: number): EasingName;
  function cubicBezier(x1: number, y1: number, x2: number, y2: number): EasingName;
  function steps(n: number): EasingName;
  function rng(seed?: number): () => number;
  const presets: {
    filmGrain(uniforms?: { amount?: number; tint?: [number, number, number] }, opts?: ShaderProps): SceneNode;
    vignette(uniforms?: { intensity?: number; smoothness?: number }, opts?: ShaderProps): SceneNode;
    chromaticAberration(uniforms?: { shift?: number }, opts?: ShaderProps): SceneNode;
    colorGrade(uniforms?: { contrast?: number; saturation?: number; brightness?: number; gamma?: number }, opts?: ShaderProps): SceneNode;
    scanlines(uniforms?: { density?: number; opacity?: number }, opts?: ShaderProps): SceneNode;
  };
}
"#;

/// Return the TypeScript `.d.ts` ambient declaration schema.
pub const fn typescript_dts() -> &'static str {
    KINE_DTS
}

/// Errors raised anywhere in the script pipeline.
#[derive(Debug, thiserror::Error)]
pub enum ScriptError {
    #[error("transpile error: {0}")]
    Transpile(String),

    #[error("javascript runtime error: {0}")]
    Runtime(String),

    #[error("script did not return a value")]
    NoReturn,

    #[error("script must return an object, got {0}")]
    NotAnObject(String),

    #[error("invalid scene json: {0}")]
    Json(String),

    #[error(transparent)]
    Authoring(#[from] AuthoringError),
}
